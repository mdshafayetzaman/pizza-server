export async function seedDemoMenuItems(db) {
  const menuItems = db.collection('menuItems')
  const now = new Date()

  for (const item of DEMO_ITEMS) {
    const _id = demoObjectId(item.demoKey)
    const doc = {
      _id,
      vendorId: DEMO_VENDOR_ID,
      vendorName: 'PizzaHub Demo',
      vendorEmail: 'demo@pizzahub.local',
      itemName: item.itemName,
      pizzaName: item.itemName,
      name: item.itemName,
      category: item.category,
      description: item.description,
      price: item.price,
      location: 'PizzaHub Demo Kitchen',
      imageUrl: item.imageUrl,
      image: item.imageUrl,
      images: [item.imageUrl],
      approvalStatus: 'approved',
      status: 'approved',
      availability: 'active',
      isActive: true,
      isAvailable: true,
      preparationTime: item.preparationTime,
      rating: item.rating,
      reviews: item.reviews,
      popular: Boolean(item.popular),
      toppings: item.toppings,
      calories: item.calories,
      isDemo: true,
      demoKey: item.demoKey,
      createdAt: now,
      updatedAt: now,
    }

    await menuItems.updateOne(
      { $or: [{ _id }, { demoKey: item.demoKey }] },
      { $setOnInsert: doc },
      { upsert: true }
    )
  }

  console.log(`Demo menu items ensured (${DEMO_ITEMS.length})`)
}

